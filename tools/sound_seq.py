"""Generate src/sound_seq.h: per sound id and voice, the note events of the original sound scripts.
usage: python3 sound_seq.py game_blob.bin > ../src/sound_seq.h
Ops (index = (byte-0x80)/4): 0 volume, 3 duration units, 4 rest, 5 tempo (ticks per unit = $2ee/arg), 7 envelope (ignored), 10 repeat n, 11 end of block / stop,
14/15 transpose, 20 instrument, 21 goto, 2 stop. Timing (units * tempo, 50 Hz ticks) is an estimate."""
import struct,sys
d=open(sys.argv[1],'rb').read();B=0xb8
rb=lambda a:d[a-B]
rw=lambda a:struct.unpack('>H',d[a-B:a-B+2])[0]
rl=lambda a:struct.unpack('>I',d[a-B:a-B+4])[0]
NOARG={2,4,11,13,17,19}
def voice(si):
    a=rl(0x16940+si*4);inst=None;vol=0x20;dur=1;tempo=2;trans=0;ev=[];loops=[];seen=set();steps=0
    while steps<600 and len(ev)<48:
        steps+=1;o=rb(a);a+=1
        if o>=0x80:
            i=(o-0x80)//4
            arg=None
            if i not in NOARG:arg=rb(a);a+=1
            if i==0:vol=arg
            elif i==3:dur=arg
            elif i==4:ev.append((-1,0,0,max(1,dur*tempo)))
            elif i==5:tempo=max(1,0x2ee//arg) if arg else tempo
            elif i==10:pass   # arg 2 in sounds 6/26/28/62: measured in the emulator (Paula log of sound 26), the block after it plays ONCE, it is not a repeat count
            elif i==11:break  # end of the script (also ends the block that follows op 10)
            elif i==14:trans+=arg if arg<128 else arg-256
            elif i==15:trans=arg if arg<128 else arg-256
            elif i==20:inst=arg
            elif i==21:
                if arg in seen:break
                seen.add(arg);a=rl(0x16940+arg*4)
            elif i==2:break
        else:
            if inst is None or inst>13 and False:continue
            pt=rl(0x375be+inst*14+10);per=rw(pt+(o*4+trans)*2)
            ev.append((inst-9 if inst>=9 else 65+inst,per,vol,max(1,dur*tempo)))
    while ev and ev[-1][0]<0:ev.pop()
    return ev
out=[];idx=[]
for s in range(69):
    r=d[0x1596e+s*6-B:0x1596e+s*6-B+6];row=[]
    for x in r[2:6]:
        if not x:row.append((len(out),0));continue
        e=voice(x);row.append((len(out),len(e)));out+=e
    idx.append(row)
print('/* Generated by tools/sound_seq.py from the original sound scripts. ticks = 50 Hz units (estimate). */')
print('typedef struct { short sample, period, vol, ticks; } SndEv;')
print('/* synth instruments 0..8: single-cycle waveforms looped by the player (sample ids 65..73) */')
print('static const unsigned char SYN_LEN[9] = {%s};'%','.join(str(2*struct.unpack('>H',d[0x375be+n*14+4-B:0x375be+n*14+6-B])[0]) for n in range(9)))
print('static const signed char SYN_DATA[9][64] = {')
for n in range(9):
    ln=2*struct.unpack('>H',d[0x375be+n*14+4-B:0x375be+n*14+6-B])[0];ad=struct.unpack('>I',d[0x375be+n*14+6-B:0x375be+n*14+10-B])[0]
    w=list(d[ad-B:ad-B+ln])+[0]*(64-ln);print('  {%s},'%','.join(str(x-256 if x>127 else x) for x in w))
print('};')
print('static const SndEv SND_EV[] = {')
for e in out:print('  {%d,%d,%d,%d},'%e)
if not out:print('  {-1,0,0,0}')
print('};')
print('static const unsigned short SND_IDX[69][4][2] = {')
for row in idx:print('  {'+','.join('{%d,%d}'%p for p in row)+'},')
print('};')
