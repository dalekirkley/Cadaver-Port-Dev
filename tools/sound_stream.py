"""Generate src/sound_stream.h from Paula register logs of the ORIGINAL sound engine.
usage: python3 sound_stream.py game_blob.bin logdir > ../src/sound_stream.h
logdir holds s<id>.txt = emulator audw.txt (6000 video frames) of a run in which the original
$152c6 (play sound d0) was called at video frame T=3150 and then patched to RTS at frame 3153 so no other game sound interferes; base.txt = the same run without the call (subtracted, should be idle writes only)
Lines: "<frame> pc=<pc> reg=<reg> v=<val>"; regs $a0..$df are Paula channel registers
(+0 LCH +2 LCL +4 LEN +6 PER +8 VOL) and $96 is DMACON.
Output: per sound a list of state-change events (frame at 50 Hz, channel, kind, value) and a bank of the sample
buffers the engine pointed Paula at (read from the game image at the same RAM addresses)."""
import struct,sys,os
blob=open(sys.argv[1],'rb').read();LD=sys.argv[2];T=3150;B=0xb8;CAP=1800
def load(path):
    ev=[]
    for l in open(path):
        p=l.split();f=int(p[0])
        if f<T+1: continue
        ev.append((f-T-1,int(p[2][4:],16),int(p[3][2:],16)))
    return ev
base=[e for e in load(LD+'/base.txt') if e[0]>=270]
from collections import Counter
bc=Counter(base)
K_LC,K_LEN,K_PER,K_VOL,K_ON,K_OFF=range(6)
def stream(ev):
    """raw register writes -> state-change events (frame,ch,kind,val); LC is the full 24-bit address here"""
    st=[dict(lc=None,len=None,per=None,vol=None) for _ in range(4)];dma=0;out=[]
    for f,r,v in ev:
        if r==0x96:
            nd=(dma|(v&0xf)) if v&0x8000 else (dma&~(v&0xf))
            for c in range(4):
                if (nd>>c&1)!=(dma>>c&1): out.append((f,c,K_ON if nd>>c&1 else K_OFF,0))
            dma=nd;continue
        c=(r-0xa0)>>4;sub=r&0xf;s=st[c]
        if sub==0:s['lch']=v;continue
        if sub==2:
            lc=(s.get('lch',0)<<16)|v
            if s['lc']!=lc:out.append((f,c,K_LC,lc));s['lc']=lc
        elif sub==4:
            if s['len']!=v:out.append((f,c,K_LEN,v));s['len']=v
        elif sub==6:
            if s['per']!=v:out.append((f,c,K_PER,v));s['per']=v
        elif sub==8:
            v&=0x7f
            if s['vol']!=v:out.append((f,c,K_VOL,v));s['vol']=v
    return out,st
allev={};bank={};loops={}   # lc -> max length in words
for i in range(69):
    p=LD+'/L%d.txt'%i
    if not os.path.exists(p):p=LD+'/s%d.txt'%i
    ev=load(p)
    bcc=Counter(bc)
    ev2=[]
    for e in ev:
        if e[0]>=270 and bcc[e]>0:bcc[e]-=1;continue
        ev2.append(e)
    # only keep frames up to the sound's own end: drop events once all used channels are idle for good
    out,st=stream(ev2)
    used=sorted({c for f,c,k,v in out if not (k==K_LC and v==0x375be)} )
    out=[e for e in out if e[1] in used or True]
    # channels the sound drives = those that ever get a non-idle buffer or volume
    drv={c for c in range(4) if blob[0x1596e+i*6+2+c-B]}   # the channels whose script byte in the sound table is nonzero
    # find the end: last event touching a driven channel
    out=[e for e in out if e[1] in drv]
    # simulate to find buffer lengths used
    cur=[dict(lc=0,len=0,on=0) for _ in range(4)];fi=0
    for f,c,k,v in out:
        s=cur[c]
        if k==K_LC:s['lc']=v
        elif k==K_LEN:s['len']=v
        elif k==K_ON:s['on']=1
        elif k==K_OFF:s['on']=0
        if s['on'] and s['len'] and s['lc']:
            bank[s['lc']]=max(bank.get(s['lc'],0),s['len'])
        last=out[-1][0] if out else 0;byf={}
    for f,c,k,v in out:byf.setdefault(f,[]).append((c,k,v))
    lp=(0,0)
    if last>=2500:   # still running when the capture stopped: find the loop (smallest period, earliest start)
        for P in range(2,1200):
            S=last-P
            while S>0 and byf.get(S-1)==byf.get(S-1+P):S-=1
            if S<=last-3*P:lp=(S,P);break
        assert lp[1],i
        if lp[0]>=CAP:   # long non-repeating run before it loops (scripts of many seconds): the port stops these after CAP frames
            out=[e for e in out if e[0]<CAP]+[(CAP,c,K_VOL,0) for c in sorted(drv)];lp=(0,0)
        else:out=[e for e in out if e[0]<lp[0]+lp[1]]
    allev[i]=out;loops[i]=lp
lcs=sorted(bank);bi={a:n for n,a in enumerate(lcs)}
print('/* Generated by tools/sound_stream.py: exact Paula register streams of the original sound engine (50 Hz frames). */')
print('typedef struct { unsigned short frame; unsigned char ch, kind; unsigned short a; } SndStreamEv;   /* kind: 0 buffer, 1 length (words), 2 period, 3 volume, 4 DMA on, 5 DMA off */')
off=[];data=bytearray()
for a in lcs:
    off.append(len(data));data+=blob[a-B:a-B+2*bank[a]]
print('static const unsigned int SSB_OFF[%d] = {%s};'%(len(lcs),','.join(map(str,off))))
print('static const unsigned short SSB_LEN[%d] = {%s};   /* bytes */'%(len(lcs),','.join(str(2*bank[a]) for a in lcs)))
print('static const signed char SSB_DATA[%d] = {'%len(data))
for k in range(0,len(data),32):print(','.join(str(x-256 if x>127 else x) for x in data[k:k+32])+',')
print('};')
print('static const SndStreamEv SSEV[] = {')
idx=[];n=0
for i in range(69):
    idx.append((n,len(allev[i])));
    for f,c,k,v in allev[i]:
        a=bi.get(v,0) if k==K_LC else v
        if k==K_LC and v not in bi:a=0xffff
        print('{%d,%d,%d,%d},'%(f,c,k,a));n+=1
print('};')
print('static const unsigned int SSIDX[69][2] = {%s};   /* first event, count */'%','.join('{%d,%d}'%x for x in idx))
print('static const unsigned short SSLOOP[69][2] = {%s};   /* loop start frame, period (0 = plays once); looping sounds run until stopped */'%','.join('{%d,%d}'%loops[i] for i in range(69)))
print('static const unsigned char SNDTAB[69][6] = {%s};   /* original table $1596e: priority (bit 7 = queued/looping), flags, scripts for channels 0..3 */'%','.join('{'+','.join(str(blob[0x1596e+i*6+j-B]) for j in range(6))+'}' for i in range(69)))
